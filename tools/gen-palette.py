#!/usr/bin/env python3
#
# Generate the framework dynamic-colour overlay from the Yugen seed palette.
#
#   ./tools/gen-palette.py
#
# Writes overlay/common/frameworks/base/core/res/res/values/yugen_colors.xml.
# Run this after changing a seed; never edit the generated XML by hand, or the
# ramp loses its perceptual spacing.
#
# Method: seeds are converted to CIE Lab. Material's "tone" is L*, so each of
# the 13 tones is produced by setting L* and keeping the seed hue, with chroma
# tapered toward white and black and reduced until the colour fits sRGB. This
# is close enough to Material's HCT ramps for a build-time default palette and
# has no dependencies beyond the standard library.
#
# SPDX-License-Identifier: Apache-2.0
#
import math
from pathlib import Path

TONES = (0, 10, 50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 1000)

# group, seed, chroma scale, description. Chroma scale < 1 mutes the ramp
# without changing its hue, which is how the one-accent scheme stays coherent.
GROUPS = (
    ("accent1", "#C8442B", 1.00, "shu / vermillion  #C8442B"),
    ("accent2", "#C8442B", 0.55, "shu, muted (accent1 at reduced chroma)"),
    ("accent3", "#B08C4F", 1.00, "kintsugi / gold  #B08C4F"),
    ("neutral1", "#1C1B1A", 1.00, "sumi / ink  #1C1B1A"),
    ("neutral2", "#6B6259", 1.00, "warm grey  #6B6259"),
)

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!--
  Project Yugen — framework dynamic-colour defaults.

  These override the stock Material tonal palettes, so a fresh install is
  sumi-and-shu before the user has chosen anything. They are defaults only:
  wallpaper-based dynamic colour still overrides them at runtime when enabled.

  Generated by tools/gen-palette.py from five seeds, each expanded to a
  13-tone ramp in CIE Lab (tone == L*, chroma tapered toward white and black).
  Do not hand-tune a single tone; change a seed and regenerate the ramp.

    sumi      #1C1B1A   ink          neutral1
    warm grey #6B6259                neutral2
    shu       #C8442B   vermillion   accent1
    kintsugi  #B08C4F   gold         accent3
    ai        #2E4A62   indigo       reserved
    matcha    #6B7F5C   tea green    reserved
    sakura    #E7B7B0   cherry       reserved

  accent2 is shu at reduced chroma; three fully saturated accents would fight
  each other, and Yugen is a one-accent scheme. The reserved colours are
  recorded here so they are not invented twice under different names.

  SPDX-License-Identifier: Apache-2.0
-->
<resources>
"""


def srgb_to_lin(c: float) -> float:
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def lin_to_srgb_byte(c: float) -> int:
    c = max(0.0, min(1.0, c))
    v = 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
    return round(max(0.0, min(1.0, v)) * 255)


def _f(t: float) -> float:
    return t ** (1 / 3) if t > (6 / 29) ** 3 else t / (3 * (6 / 29) ** 2) + 4 / 29


def _finv(t: float) -> float:
    return t ** 3 if t ** 3 > (6 / 29) ** 3 else 3 * (6 / 29) ** 2 * (t - 4 / 29)


def hex_to_lab(h: str) -> tuple[float, float, float]:
    h = h.lstrip("#")
    r, g, b = (srgb_to_lin(int(h[i:i + 2], 16) / 255) for i in (0, 2, 4))
    x = r * 0.4124564 + g * 0.3575761 + b * 0.1804375
    y = r * 0.2126729 + g * 0.7151522 + b * 0.0721750
    z = r * 0.0193339 + g * 0.1191920 + b * 0.9503041
    fx, fy, fz = _f(x / 0.95047), _f(y), _f(z / 1.08883)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def _lab_to_xyz(L: float, a: float, b: float) -> tuple[float, float, float]:
    fy = (L + 16) / 116
    return 0.95047 * _finv(fy + a / 500), _finv(fy), 1.08883 * _finv(fy - b / 200)


def _in_gamut(L: float, a: float, b: float) -> bool:
    x, y, z = _lab_to_xyz(L, a, b)
    r = 3.2404542 * x - 1.5371385 * y - 0.4985314 * z
    g = -0.9692660 * x + 1.8760108 * y + 0.0415560 * z
    bl = 0.0556434 * x - 0.2040259 * y + 1.0572252 * z
    return all(-0.0005 <= v <= 1.0005 for v in (r, g, bl))


def tone(seed: str, tone_value: int, chroma_scale: float) -> str:
    """Return a hex colour with L* == tone_value/10 and the seed's hue."""
    L = (1000 - tone_value) / 10.0  # AOSP numbers tones white -> black
    _, a, b = hex_to_lab(seed)
    chroma = math.hypot(a, b)
    a, b = (a / chroma, b / chroma) if chroma > 1e-6 else (0.0, 0.0)

    # Full chroma through the midtones, fading to neutral at both ends.
    t = L / 100.0
    envelope = max(0.0, min(1.0, 1.0 - (abs(t - 0.55) / 0.55) ** 2.2))
    chroma *= chroma_scale * envelope

    while chroma > 0.05 and not _in_gamut(L, a * chroma, b * chroma):
        chroma *= 0.97

    x, y, z = _lab_to_xyz(L, a * chroma, b * chroma)
    r = lin_to_srgb_byte(3.2404542 * x - 1.5371385 * y - 0.4985314 * z)
    g = lin_to_srgb_byte(-0.9692660 * x + 1.8760108 * y + 0.0415560 * z)
    bl = lin_to_srgb_byte(0.0556434 * x - 0.2040259 * y + 1.0572252 * z)
    return f"#{r:02X}{g:02X}{bl:02X}"


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    out = root / "overlay/common/frameworks/base/core/res/res/values/yugen_colors.xml"

    lines = [HEADER.rstrip("\n"), ""]
    for group, seed, scale, note in GROUPS:
        lines.append(f"  <!-- ==== {note} ==== -->")
        for theme in ("light", "dark"):
            lines.append(f"    <!-- {theme} -->")
            for t in TONES:
                lines.append(
                    f'    <color name="system_{group}_{t}_{theme}">'
                    f"{tone(seed, t, scale)}</color>"
                )
            lines.append("")
    lines.append("</resources>")

    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(root)}")


if __name__ == "__main__":
    main()
